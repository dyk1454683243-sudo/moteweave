#!/usr/bin/env node
// VIS-01 inline SVG sprite builder.
// The maintained server.js serves *.svg as application/octet-stream, so the
// Figma-exported assets in ./assets are inlined verbatim as <symbol> elements
// between the sprite markers in vnext-preview.html and referenced with
// <svg><use href="#vnext-<name>"/></svg>. Graphics, viewBox, colors, and sizes
// are kept as exported; only ids are namespaced per symbol (referenced ids are
// rewritten consistently, unreferenced decorative ids are dropped).
//
//   node src/ui/vnext/vnext-preview-sprite.mjs        # rewrite the sprite block
//   node src/ui/vnext/vnext-preview-sprite.mjs --check # exit 1 when out of sync

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export const SPRITE_START = '<!-- vnext-sprite:start · generated by vnext-preview-sprite.mjs from ./assets/*.svg · do not edit by hand -->'
export const SPRITE_END = '<!-- vnext-sprite:end -->'

const HERE = path.dirname(fileURLToPath(import.meta.url))
export const ASSETS_DIR = path.join(HERE, 'assets')
export const HTML_FILE = path.join(HERE, 'vnext-preview.html')

export function symbolId(fileName) {
  return `vnext-${path.basename(fileName, '.svg')}`
}

// Convert one exported SVG document into a <symbol>. Returns null for non-SVG files.
export function toSymbol(fileName, svgText) {
  const open = svgText.match(/^\s*<svg\b([^>]*)>/)
  const closeIndex = svgText.lastIndexOf('</svg>')
  if (!open || closeIndex < 0) throw new Error(`${fileName}: not an SVG document`)
  const rootAttrs = open[1]
  const viewBox = rootAttrs.match(/\bviewBox="([^"]+)"/)?.[1]
  if (!viewBox) throw new Error(`${fileName}: root <svg> has no viewBox`)
  const rootFill = rootAttrs.match(/\bfill="([^"]+)"/)?.[1]
  let inner = svgText.slice(open[0].length, closeIndex)

  // Namespace ids: rewrite referenced ids consistently, drop unreferenced ones.
  const id = symbolId(fileName)
  const referenced = new Set()
  for (const match of inner.matchAll(/url\(#([^)]+)\)/g)) referenced.add(match[1])
  for (const match of inner.matchAll(/\bhref="#([^"]+)"/g)) referenced.add(match[1])
  inner = inner.replace(/\sid="([^"]*)"/g, (_, value) => (referenced.has(value) ? ` id="${id}-${value}"` : ''))
  inner = inner.replace(/url\(#([^)]+)\)/g, (_, value) => `url(#${id}-${value})`)
  inner = inner.replace(/\bhref="#([^"]+)"/g, (_, value) => `href="#${id}-${value}"`)
  inner = inner.replace(/\n{2,}/g, '\n').trim()

  const attrs = [`id="${id}"`, `viewBox="${viewBox}"`]
  if (rootFill) attrs.push(`fill="${rootFill}"`)
  return `<symbol ${attrs.join(' ')}>\n${inner}\n</symbol>`
}

export function buildSprite(assetsDir = ASSETS_DIR) {
  const files = readdirSync(assetsDir).filter((name) => name.endsWith('.svg')).sort()
  const symbols = files.map((name) => toSymbol(name, readFileSync(path.join(assetsDir, name), 'utf8')))
  return `${SPRITE_START}\n<svg xmlns="http://www.w3.org/2000/svg" class="vnext-sprite" aria-hidden="true" focusable="false">\n${symbols.join('\n')}\n</svg>\n${SPRITE_END}`
}

export function spriteBlockOf(html) {
  const start = html.indexOf(SPRITE_START)
  const end = html.indexOf(SPRITE_END)
  if (start < 0 || end < 0 || end < start) return null
  return html.slice(start, end + SPRITE_END.length)
}

export function injectSprite(html, sprite) {
  const current = spriteBlockOf(html)
  if (!current) throw new Error('sprite markers not found in vnext-preview.html')
  return html.replace(current, sprite)
}

function main(argv) {
  const check = argv.includes('--check')
  const html = readFileSync(HTML_FILE, 'utf8')
  const sprite = buildSprite()
  const inSync = spriteBlockOf(html) === sprite
  if (check) {
    if (!inSync) {
      console.error('vnext-preview.html sprite block is out of sync with ./assets/*.svg')
      process.exit(1)
    }
    console.log('sprite in sync')
    return
  }
  if (inSync) {
    console.log('sprite already in sync')
    return
  }
  writeFileSync(HTML_FILE, injectSprite(html, sprite))
  console.log(`sprite rewritten: ${sprite.length} bytes`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2))
}
