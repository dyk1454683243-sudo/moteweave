let currentLanguage = 'zh'

function safeStorage() {
  try {
    return globalThis.localStorage
  } catch {
    return null
  }
}

export function normalizeLanguage(language) {
  const value = String(language || '').toLowerCase()
  if (value.startsWith('zh')) return 'zh'
  if (value.startsWith('en')) return 'en'
  return null
}

function documentLanguage() {
  if (typeof document === 'undefined') return 'zh'
  return normalizeLanguage(document.documentElement.getAttribute('lang')) || 'zh'
}

function storedLanguage(storage = safeStorage()) {
  if (!storage) return null
  try {
    return normalizeLanguage(storage.getItem(LANGUAGE_STORAGE_KEY))
  } catch {
    return null
  }
}

function persistLanguage(language, storage = safeStorage()) {
  if (!storage) return
  try {
    storage.setItem(LANGUAGE_STORAGE_KEY, language)
  } catch {
    // Ignore blocked localStorage; the UI can still switch for this session.
  }
}

function replacementsFromElement(element) {
  const replacements = {}
  for (const attribute of element.attributes) {
    if (!attribute.name.startsWith('data-i18n-var-')) continue
    replacements[attribute.name.slice('data-i18n-var-'.length)] = attribute.value
  }
  return replacements
}

export function t(key, replacements = {}, language = currentLanguage) {
  const lang = normalizeLanguage(language) || 'zh'
  const template = TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? key
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => String(replacements[name] ?? ''))
}

const TRANSLATED_ATTRIBUTES = {
  i18nPlaceholder: 'placeholder',
  i18nTitle: 'title',
  i18nAriaLabel: 'aria-label',
  i18nAlt: 'alt',
}

function translateAttribute(root, selector, datasetKey, language) {
  root.querySelectorAll(selector).forEach((element) => {
    const key = element.dataset[datasetKey]
    if (!key) return
    element.setAttribute(TRANSLATED_ATTRIBUTES[datasetKey], t(key, {}, language))
  })
}

export function translateDocument(root = document, language = currentLanguage) {
  if (!root?.querySelectorAll) return
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n, replacementsFromElement(element), language)
  })
  translateAttribute(root, '[data-i18n-placeholder]', 'i18nPlaceholder', language)
  translateAttribute(root, '[data-i18n-title]', 'i18nTitle', language)
  translateAttribute(root, '[data-i18n-aria-label]', 'i18nAriaLabel', language)
  translateAttribute(root, '[data-i18n-alt]', 'i18nAlt', language)
}

export function getCurrentLanguage() {
  return currentLanguage
}

export function setCurrentLanguage(language, { persist = true } = {}) {
  currentLanguage = normalizeLanguage(language) || 'zh'
  if (typeof document !== 'undefined') {
    document.documentElement.lang = currentLanguage === 'zh' ? 'zh-CN' : 'en'
    const select = document.querySelector('#language-select')
    if (select) select.value = currentLanguage
    translateDocument(document, currentLanguage)
  }
  if (persist) persistLanguage(currentLanguage)
  return currentLanguage
}

export function initI18n() {
  const language = storedLanguage() || documentLanguage()
  setCurrentLanguage(language, { persist: false })
  const select = typeof document === 'undefined' ? null : document.querySelector('#language-select')
  if (!select) return
  select.value = currentLanguage
  select.addEventListener('change', () => {
    setCurrentLanguage(select.value)
  })
}
